export type QaSeverity = 'Blocker' | 'Critical' | 'High' | 'Medium' | 'Low' | 'Info';
export type QaCategory =
  | 'Functional'
  | 'UI/UX'
  | 'Responsive'
  | 'Security'
  | 'Data Integrity'
  | 'Print/PDF'
  | 'A11y'
  | 'Performance';
/** Status v2.0. 'Verified' = temuan v1.0 yang sudah diperiksa ulang pada audit ini. */
export type QaStatus = 'Open' | 'Fixed' | 'Verified' | 'Deferred' | 'Accepted';
/** Status pada laporan v1.0, atau 'Baru' bila temuan pertama kali muncul di v2.0. */
export type QaV1Status = 'Baru' | 'Open' | 'Fixed' | 'Deferred' | 'Accepted';

export type QaFinding = {
  id: string;
  title: string;
  severity: QaSeverity;
  category: QaCategory;
  /** Status setelah audit v2.0. */
  status: QaStatus;
  /** Status pada laporan v1.0 — dasar kolom "v1.0 → v2.0". */
  v1Status: QaV1Status;
  /** Fase audit tempat temuan ditemukan (F1–F8). */
  phase: string;
  area: string;
  route?: string;
  evidence: string;
  evidenceImage?: string;
  expected: string;
  actual: string;
  reproduction: string[];
  errorCode?: string;
  /** Diagnosis cepat + langkah penanganan. */
  troubleshooting: string;
  recommendation: string;
};

export type QaPhase = {
  id: string;
  name: string;
  status: 'Selesai' | 'Sebagian';
  evidence: string;
};

export type QaReport = {
  title: string;
  subtitle: string;
  version: string;
  date: string;
  /** Daftar isi — 12 bab. Nomor halaman diisi oleh render dua-pass. */
  toc: Array<{ id: string; title: string }>;
  phases: QaPhase[];
  scope: string[];
  environment: Array<{ label: string; value: string }>;
  summary: Array<{ label: string; value: string }>;
  features: Array<{ area: string; route: string; status: string; notes: string }>;
  /** Hasil terukur (bukti objektif) untuk bab UI/UX. */
  measurements: Array<{ group: string; rows: Array<{ label: string; value: string; verdict: string }> }>;
  findings: QaFinding[];
  /** Matriks perubahan status v1.0 → v2.0 per temuan. */
  statusMatrixNote: string;
  positives: string[];
  /** Pengujian tambahan yang belum tercakup pada audit ini. */
  additionalTests: string[];
  notes: string[];
  recommendation: string;
};

